// Package ocistore 在本地文件系统上实现了一套内容寻址的 OCI 镜像存储与
// 引用解析组件，用本地目录模拟镜像仓库。
//
// 核心能力：
//
//   - 按标签或摘要写入/读取内容，相同内容去重，标签可迁移而摘要固定内容不变；
//   - 从镜像索引解析到具体平台清单，平台缺失/清单截断/摘要不符均明确拒绝；
//   - 基于内容寻址的完整性校验，损坏内容被隔离且不再作为缓存命中返回；
//   - 原子发布保证并发读写不出现半写入内容或未完成清单；
//   - 引用计数式可达性 GC，与并发拉取通过门闩互斥，避免悬空/误删/复活；
//   - 可配置存储配额，超限明确拒绝并回滚，不留临时状态；
//   - 兼容 OCI 与 Docker v2 清单格式，未知媒体类型明确拒绝，额外字段容忍。
//
// 典型用法与语义详见 README.md。
